def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Cluster images in a folder using K-Means + MobileNetV2 features."
    )
    parser.add_argument(
        "--images-dir", "-i",
        default="dataset",
        help="Subfolder (relative to project root) containing source images. "
             "Default: 'dataset'",
    )
    parser.add_argument(
        "--output-dir", "-o",
        default="clustered",
        help="Subfolder where cluster_N/ folders will be created. "
             "Default: 'clustered'",
    )
    parser.add_argument(
        "--k", "-k",
        type=int, default=2,
        help="Number of clusters. Default: 2 (cats / dogs)",
    )
    parser.add_argument(
        "--batch-size", "-b",
        type=int, default=32,
        help="Images per inference batch. Reduce if you run out of memory. Default: 32",
    )
    parser.add_argument(
        "--pca-variance", "-p",
        type=float, default=0.95,
        help="Fraction of variance to keep after PCA (0–1). Default: 0.95",
    )
    parser.add_argument(
        "--move",
        action="store_true",
        help="Move files instead of copying (saves disk space).",
    )
    return parser.parse_args()


def main() -> None:
    args = parse_args()

    # ── Project root = directory of this script ───────────────────────────────
    project_root = Path(__file__).resolve().parent

    images_dir  = project_root / args.images_dir
    output_dir  = project_root / args.output_dir
    logs_dir    = project_root / "logs"

    logger = setup_logger(logs_dir)

    logger.info("=" * 60)
    logger.info("  IMAGE CLUSTERER  —  K-Means + MobileNetV2")
    logger.info("=" * 60)
    logger.info(f"  Project root : {project_root}")
    logger.info(f"  Images dir   : {images_dir}")
    logger.info(f"  Output dir   : {output_dir}")
    logger.info(f"  k (clusters) : {args.k}")
    logger.info(f"  Batch size   : {args.batch_size}")
    logger.info(f"  PCA variance : {args.pca_variance}")
    logger.info(f"  Move files   : {args.move}")
    logger.info("=" * 60)

    # Check that the images directory exists
    if not images_dir.exists():
        logger.error(f"Images directory not found: {images_dir}")
        logger.error("  → Create the folder and place your images there, then re-run.")
        sys.exit(1)

    # ── Pipeline ──────────────────────────────────────────────────────────────
    t_start = time.time()

    # 1. Collect paths
    all_paths = collect_image_paths(images_dir, logger)

    # 2. Build extractor & extract features
    extractor = build_feature_extractor(logger)
    features, valid_paths = extract_features(all_paths, extractor,
                                             args.batch_size, logger)

    # 3. PCA
    reduced = reduce_with_pca(features, args.pca_variance, logger)

    # 4. K-Means
    labels = cluster_features(reduced, args.k, logger)

    # 5. Copy/move files
    copy_to_clusters(valid_paths, labels, output_dir, logger, move=args.move)

    # ── Summary ───────────────────────────────────────────────────────────────
    total_time = time.time() - t_start
    logger.info("=" * 60)
    logger.info("  FINISHED SUCCESSFULLY")
    logger.info(f"  Total time   : {total_time:.1f}s  ({total_time/60:.1f} min)")
    logger.info(f"  Images sorted: {len(valid_paths)}")
    logger.info(f"  Output       : {output_dir}")
    logger.info("=" * 60)


if __name__ == "__main__":
    main()
